    fun getDailyQuote(): String {
        val today = Calendar.getInstance().get(Calendar.DAY_OF_YEAR)
        return quotes[today % quotes.size]
    }

    fun getRandomQuote(): String {
        return quotes[Random().nextInt(quotes.size)]
    }

    fun getDailyPrediction(): String {
        val today = Calendar.getInstance().get(Calendar.DAY_OF_YEAR)
        return predictions[(today * 7) % predictions.size]
    }

    fun getRandomPrediction(): String {
        return predictions[Random().nextInt(predictions.size)]
